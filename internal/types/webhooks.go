type CreateWebhookRequest struct {
	Name   string         `json:"name"`
	URL    string         `json:"url"`
	Events []WebhookEvent `json:"events"`
	Secret string         `json:"secret,omitempty"`
	Active *bool          `json:"active,omitempty"`
}

func (r *CreateWebhookRequest) Validate() error {
	if r.URL == "" {
		return errors.New("webhook: url is required")
	}
	if len(r.Events) == 0 {
		return errors.New("webhook: at least one event is required")
	}
	for _, e := range r.Events {
		if !ValidWebhookEvents[e] {
			return errors.New("webhook: unknown event " + string(e))
		}
	}
	if r.Secret != "" && len(r.Secret) < 16 {
		return errors.New("webhook: secret must be at least 16 chars when provided")
	}
	return nil
}

