// Package types — Build #46.x Webhook data model.
//
// A Webhook is a tenant-owned outbound subscription: "when event X
// fires, POST the payload to URL Y". Each subscription signs its
// outbound requests with an HMAC-SHA256 of the body using the row's
// Secret, so receivers can verify the source without trusting TLS
// alone.
package types

import (
	"database/sql/driver"
	"encoding/json"
	"errors"
	"time"
)

// WebhookEvent names one of the closed set of events that can flow
// through the outbound webhook bus.
type WebhookEvent string

