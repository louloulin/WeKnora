// WebhookEventList is the storage representation of the subscription
// event allow-list. The column is JSONB (mysql TEXT) so we implement
// sql.Scanner / driver.Valuer round-tripping here.
type WebhookEventList []WebhookEvent

// Value marshals the list to JSON for storage.
func (l WebhookEventList) Value() (driver.Value, error) {
	if l == nil {
		return "[]", nil
	}
	return json.Marshal([]WebhookEvent(l))
}

// Scan parses JSON bytes from storage back into the list.
func (l *WebhookEventList) Scan(src interface{}) error {
	if src == nil {
		*l = nil
		return nil
	}
	var b []byte
	switch v := src.(type) {
	case []byte:
		b = v
	case string:
		b = []byte(v)
	default:
		return errors.New("webhook events: unsupported scan source")
	}
	if len(b) == 0 {
		*l = nil
		return nil
	}
	var out []WebhookEvent
	if err := json.Unmarshal(b, &out); err != nil {
		return err
	}
	*l = out
	return nil
}

// MarshalJSON serialises the list as a JSON array.
func (l WebhookEventList) MarshalJSON() ([]byte, error) {
	if l == nil {
		return []byte("[]"), nil
	}
	return json.Marshal([]WebhookEvent(l))
}

// UnmarshalJSON parses a JSON array into the list.
func (l *WebhookEventList) UnmarshalJSON(b []byte) error {
	var out []WebhookEvent
	if err := json.Unmarshal(b, &out); err != nil {
		return err
	}
	*l = out
	return nil
}

// Contains reports whether the given event is in the list.
func (l WebhookEventList) Contains(e WebhookEvent) bool {
	for _, x := range l {
		if x == e {
			return true
		}
	}
	return false
}

// Webhook is the row representation.
type Webhook struct {
	ID             string          `json:"id"             gorm:"primaryKey;type:varchar(36)"`
	TenantID       uint64          `json:"tenant_id"      gorm:"index"`
	Name           string          `json:"name"           gorm:"type:varchar(128)"`
	URL            string          `json:"url"            gorm:"type:varchar(512)"`
	Events         WebhookEventList `json:"events"        gorm:"type:text"`
	Secret         string          `json:"-"              gorm:"type:varchar(128)"`
	Active         bool            `json:"active"         gorm:"default:true"`
	LastDeliveryAt *time.Time      `json:"last_delivery_at,omitempty" gorm:""`
	LastError      string          `json:"last_error,omitempty"      gorm:"type:varchar(1024);default:''"`
	CreatedBy      uint64          `json:"created_by"`
	CreatedAt      time.Time       `json:"created_at"`
	UpdatedAt      time.Time       `json:"updated_at"`
}

func (Webhook) TableName() string { return "webhooks" }

